#!/usr/bin/env python3
"""selinux/tools/classes.py: the object classes and permissions of the running kernel, as CIL.

Reads security/selinux/include/classmap.h and initial_sid_to_string.h of the kernel the
policy is built for (selinux/pins/*-6.18.h, copied from kernel.org v6.18) and writes
selinux/policy/00-classes.cil: (class NAME (perms)), (classorder ...), (sid NAME),
(sidorder ...). The kernel checks the policy's classes and permissions against this map at
load: a permission the policy names and the kernel does not know is an error, one the kernel
knows and the policy does not is handled by `handleunknown`. The file is generated, never
edited: python3 -I selinux/tools/classes.py selinux/pins/classmap-6.18.h \\
                 selinux/pins/initial_sid_to_string-6.18.h > selinux/policy/00-classes.cil
"""
import re
import sys

src = open(sys.argv[1]).read()
sids_src = open(sys.argv[2]).read()

# the COMMON_* macros: name -> the list of permission strings (macros refer to earlier ones)
macros = {}
for m in re.finditer(r"#define (COMMON_\w+)\s+((?:.*\\\n)*.*)", src):
    name, body = m.group(1), m.group(2)
    perms = []
    for tok in re.findall(r'"([^"]+)"|(COMMON_\w+)', body):
        if tok[0]:
            perms.append(tok[0])
        else:
            perms.extend(macros[tok[1]])
    macros[name] = perms

# the class table
table = src[src.index("secclass_map[] = {"):]
classes = []
for m in re.finditer(r'\{\s*"(\w+)",\s*\{(.*?)NULL\s*\}\s*\}', table, re.S):
    name, body = m.group(1), m.group(2)
    perms = []
    for tok in re.findall(r'"([^"]+)"|(COMMON_\w+)', body):
        if tok[0]:
            perms.append(tok[0])
        else:
            perms.extend(macros[tok[1]])
    classes.append((name, perms))

# the initial SIDs, in the kernel's order; NULL slots keep a historical name so that the
# order (what the kernel matches by) is right
hist = ["kernel", "security", "unlabeled", "fs", "file", "file_labels", "init", "any_socket", "port", "netif",
        "netmsg", "node", "igmp_packet", "icmp_socket", "tcp_socket", "sysctl_modprobe", "sysctl", "sysctl_fs",
        "sysctl_kernel", "sysctl_net", "sysctl_net_unix", "sysctl_vm", "sysctl_dev", "kmod", "policy",
        "scmp_packet", "devnull"]
entries = re.findall(r'^\s*(NULL|"\w+"),\s*/\*\s*(\w+)', sids_src, re.M)
sids = []
for raw, comment in entries[1:]:  # the first is the zero placeholder
    sids.append(comment)
assert sids == hist, (sids, hist)

out = sys.stdout
out.write(";; selinux/policy/00-classes.cil: generated by selinux/tools/classes.py from the kernel's\n")
out.write(";; classmap.h and initial_sid_to_string.h (selinux/pins, Linux 6.18). Do not edit.\n\n")
out.write("(sidorder (" + " ".join(sids) + "))\n")
for s in sids:
    out.write(f"(sid {s})\n")
out.write("\n(classorder (" + " ".join(c for c, _ in classes) + "))\n")
for name, perms in classes:
    out.write(f"(class {name} ({' '.join(perms)}))\n")
print(f"{len(classes)} classes, {sum(len(p) for _, p in classes)} permissions, {len(sids)} initial SIDs", file=sys.stderr)
